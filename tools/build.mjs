// Builds single-file bundles from the shared libs:
//   tools/console-export.js          paste into DevTools on the AliExpress orders page
//   tools/gmail-apps-script/Code.gs  paste into script.google.com
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const header = (what) => `/* GENERATED by tools/build.mjs — edit extension/lib/* or tools/src/* instead. ${what} */\n`;

const bundles = [
  ['tools/console-export.js', 'AliExpress order export — paste into the DevTools console on https://www.aliexpress.com/p/order/index.html',
    ['extension/lib/core.js', 'extension/lib/parsers.js', 'tools/src/console-runner.js']],
  ['tools/gmail-apps-script/Code.gs', 'AliExpress Gmail backfill for Google Apps Script',
    ['extension/lib/core.js', 'extension/lib/email.js', 'tools/src/apps-script-runner.js']],
];

for (const [out, what, parts] of bundles) {
  fs.writeFileSync(path.join(root, out), header(what) + parts.map(read).join('\n'));
  console.log('wrote', out);
}
